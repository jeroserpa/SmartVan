"""Render every van-core panel screen to PNG, on a laptop, from the firmware's
own drawing code.

    & "$env:APPDATA\\uv\\tools\\esphome\\Scripts\\python.exe" tools/panel_preview/panel_preview.py

Why this exists (D-36): the panel used to be reviewed by flashing it, or by an
HTML mock-up redrawn by hand that drifted from the firmware within a week. Here
nothing is redrawn:

  * nodes/vc_panel.h and nodes/vc_draw.h - the files the firmware compiles - are
    compiled with g++ against a small stand-in for ESPHome's display API
    (shim/), which mirrors ESPHome's own pixel loops and text alignment;
  * the fonts are van-core.yaml's own `font:` list, rasterised by ESPHome's own
    glyph code (esphome.components.font.glyph_to_glyphinfo), so glyph shapes,
    metrics and 4-bit quantisation are the panel's;
  * pixels are stored as RGB565, as the panel stores them.

So a layout that is wrong here is wrong on the glass, and a glyph missing from
van-core.yaml fails this run instead of drawing a box in the van.

What it does NOT show: the panel's real gamma and viewing angle, and its exact
corner radius - `GLASS_R` in vc_panel.h is an estimate (VERIFY on the panel).

Needs: ESPHome's Python (for freetype and esphome itself - run it with the
interpreter above), g++ (MSYS2 mingw64 here), Pillow, and internet once to
fetch the fonts. Writes to tools/panel_preview/out/ (gitignored):

    <scene>.png        one screen at 3x, with the glass's rounded corners
    sheet.png          every scene on one page
    far_2m5.png        the same sheet as a 20/20 eye resolves it at 2.5 m
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

import freetype
import yaml
from PIL import Image, ImageDraw, ImageFilter, ImageFont

from esphome.components.font import glyph_to_glyphinfo, pt_to_px

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
NODES = REPO / "nodes"
CORE_YAML = NODES / "van-core.yaml"
FONT_IDS = ["f_hero", "f_unit", "f_big", "f_title", "f_body", "f_small",
            "f_icon_s", "f_icon_m", "f_icon_l", "f_soc", "f_mid"]
PW, PH = 320, 172
MM_PER_PX = 0.1028  # van-core.yaml font notes, MEASURED 2026-09-11


def glass_r() -> int:
    m = re.search(r"constexpr int GLASS_R = (\d+);", (NODES / "vc_panel.h").read_text("utf-8"))
    return int(m.group(1)) if m else 22


# ---- van-core.yaml's font list ------------------------------------------------

class _Loader(yaml.SafeLoader):
    """ESPHome YAML with every custom tag (!include, !secret, !lambda) as None."""


_Loader.add_multi_constructor("!", lambda loader, suffix, node: None)


def font_specs() -> dict[str, dict]:
    doc = yaml.load(CORE_YAML.read_text("utf-8"), Loader=_Loader)
    specs = {f["id"]: f for f in doc["font"]}
    missing = [i for i in FONT_IDS if i not in specs]
    if missing:
        sys.exit(f"van-core.yaml has no font(s) {missing} - vc_panel.h's Fonts needs them")
    return specs


def cache_dir() -> Path:
    d = Path(os.environ.get("VAN_PREVIEW_CACHE", Path(tempfile.gettempdir()) / "van-panel-preview"))
    d.mkdir(parents=True, exist_ok=True)
    return d


def _get(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "van-panel-preview"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read()


def font_file(spec) -> Path:
    """Local TTF for a `file:` value, downloaded once into the cache."""
    f = spec["file"]
    if isinstance(f, dict):
        f = f.get("url") or f.get("path") or f"gfonts://{f['family']}@{f.get('weight', 400)}"
    key = re.sub(r"[^A-Za-z0-9@._-]", "_", f)[-120:]
    path = cache_dir() / f"{key}.ttf"
    if path.exists():
        return path
    if f.startswith("gfonts://"):
        family, _, weight = f[len("gfonts://"):].partition("@")
        css = _get(f"https://fonts.googleapis.com/css2?family={family}:ital,wght@0,{weight or 400}")
        m = re.search(r"src:\s+url\((.+?)\)\s+format\('truetype'\)", css.decode())
        if not m:
            sys.exit(f"no truetype URL in Google Fonts' answer for {f}")
        path.write_bytes(_get(m.group(1)))
    elif f.startswith(("http://", "https://")):
        path.write_bytes(_get(f))
    else:
        return (NODES / f).resolve()
    return path


def glyph_chars(spec) -> list[str]:
    g = spec.get("glyphs", [])
    if isinstance(g, str):
        g = [g]
    return sorted({c for s in g for c in s}, key=ord)


# ---- fonts_gen.h ---------------------------------------------------------------

def write_fonts_header(out: Path) -> None:
    specs = font_specs()
    lines = ["// GENERATED by panel_preview.py from nodes/van-core.yaml - do not edit.",
             "#pragma once", "#include <cstdint>",
             "struct GlyphRec { uint32_t cp; int advance, offset_x, offset_y, width, height;"
             " uint32_t data_off; };",
             "struct FontRec { const char *id; int bpp, baseline, height;"
             " const GlyphRec *glyphs; int n; const uint8_t *data; };"]
    recs = []
    for fid in FONT_IDS:
        spec = specs[fid]
        face = freetype.Face(str(font_file(spec)))
        size, bpp = int(spec["size"]), int(spec.get("bpp", 1))
        data: list[int] = []
        glyphs = []
        for ch in glyph_chars(spec):
            if face.get_char_index(ord(ch)) == 0:
                sys.exit(f"{fid}: glyph U+{ord(ch):04X} is not in {spec['file']}")
            gi = glyph_to_glyphinfo(ch, face, size, bpp)
            glyphs.append((ord(ch), gi.advance, gi.offset_x, gi.offset_y, gi.width, gi.height, len(data)))
            data.extend(gi.bitmap_data)
        # The same two numbers ESPHome passes to Font(): baseline and line height.
        baseline, height = pt_to_px(face.size.ascender), pt_to_px(face.size.height)
        lines.append(f"static const uint8_t {fid}_data[] = {{{','.join(map(str, data)) or '0'}}};")
        lines.append(f"static const GlyphRec {fid}_glyphs[] = {{")
        lines += [f"  {{{cp}u,{a},{ox},{oy},{w},{h},{off}u}}," for cp, a, ox, oy, w, h, off in glyphs]
        lines.append("};")
        recs.append(f'  {{"{fid}",{bpp},{baseline},{height},{fid}_glyphs,{len(glyphs)},{fid}_data}},')
    lines.append("static const FontRec FONTS[] = {")
    lines += recs
    lines.append("};")
    lines.append(f"static const int N_FONTS = {len(recs)};")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


# ---- build and run ---------------------------------------------------------------

def find_gxx() -> str:
    for c in (os.environ.get("CXX"), shutil.which("g++"), r"C:\msys64\mingw64\bin\g++.exe"):
        if c and Path(c).exists():
            return c
    sys.exit("g++ not found - set CXX")


def build_and_run(work: Path, ppm_dir: Path, only: str | None) -> None:
    exe = work / ("render.exe" if os.name == "nt" else "render")
    cmd = [find_gxx(), "-std=gnu++20", "-O2", "-Wall", "-Wno-unused-function", "-static",
           f"-I{HERE / 'shim'}", f"-I{NODES}", f"-I{work}", str(HERE / "render.cpp"), "-o", str(exe)]
    env = dict(os.environ)
    env["PATH"] = str(Path(cmd[0]).parent) + os.pathsep + env.get("PATH", "")
    subprocess.run(cmd, check=True, env=env)
    ppm_dir.mkdir(parents=True, exist_ok=True)
    for p in ppm_dir.glob("*.ppm"):
        p.unlink()
    r = subprocess.run([str(exe), str(ppm_dir)] + ([only] if only else []), env=env)
    if r.returncode == 3:
        sys.exit("render failed: a glyph is missing from van-core.yaml (see above)")
    if r.returncode == 4:
        print("WARNING: text outside the safe area (see above) - images written anyway")
    elif r.returncode != 0:
        sys.exit(f"render failed ({r.returncode})")


# ---- pictures ------------------------------------------------------------------

def on_glass(img: Image.Image, scale: int) -> Image.Image:
    """The frame as the glass shows it: rounded corners, a sliver of bezel."""
    big = img.resize((PW * scale, PH * scale), Image.NEAREST)
    r = glass_r() * scale
    mask = Image.new("L", big.size, 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, big.width - 1, big.height - 1], r, fill=255)
    pad = 6 * scale
    out = Image.new("RGB", (big.width + 2 * pad, big.height + 2 * pad), (16, 16, 18))
    ImageDraw.Draw(out).rounded_rectangle([0, 0, out.width - 1, out.height - 1], r + pad,
                                          fill=(9, 9, 10))
    out.paste(big, (pad, pad), mask)
    return out


def far(img: Image.Image, metres: float) -> Image.Image:
    """Roughly what a 20/20 eye resolves at `metres`: 1 arcminute per sample."""
    width_arcmin = (PW * MM_PER_PX / 1000.0) / metres * (180 / 3.14159265) * 60
    n = max(8, round(width_arcmin))
    small = img.resize((n, max(4, round(n * PH / PW))), Image.BOX)
    return small.resize((PW, PH), Image.BICUBIC).filter(ImageFilter.GaussianBlur(0.6))


def sheet(frames: list[tuple[str, Image.Image]], scale: int, cols: int) -> Image.Image:
    cell_w, cell_h = PW * scale + 12 * scale + 24, PH * scale + 12 * scale + 44
    rows = (len(frames) + cols - 1) // cols
    out = Image.new("RGB", (cols * cell_w + 24, rows * cell_h + 24), (28, 28, 30))
    d = ImageDraw.Draw(out)
    try:
        label = ImageFont.truetype("arial.ttf", 18)
    except OSError:
        label = ImageFont.load_default()
    for i, (name, im) in enumerate(frames):
        x, y = 24 + (i % cols) * cell_w, 24 + (i // cols) * cell_h
        out.paste(on_glass(im, scale), (x, y))
        d.text((x, y + PH * scale + 12 * scale + 6), name, fill=(170, 170, 170), font=label)
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", type=Path, default=HERE / "out")
    ap.add_argument("--scene", help="render one scene only, e.g. 01_energy_sun")
    ap.add_argument("--scale", type=int, default=3)
    args = ap.parse_args()

    work = cache_dir()
    write_fonts_header(work / "fonts_gen.h")
    ppm = work / "ppm"
    build_and_run(work, ppm, args.scene)

    args.out.mkdir(parents=True, exist_ok=True)
    frames = []
    for p in sorted(ppm.glob("*.ppm")):
        im = Image.open(p).convert("RGB")
        frames.append((p.stem, im))
        on_glass(im, args.scale).save(args.out / f"{p.stem}.png")
    if not args.scene:
        sheet(frames, 2, 4).save(args.out / "sheet.png")
        sheet([(n, far(im, 2.5)) for n, im in frames], 2, 4).save(args.out / "far_2m5.png")
    print(f"{len(frames)} screen(s) -> {args.out}")


if __name__ == "__main__":
    main()
